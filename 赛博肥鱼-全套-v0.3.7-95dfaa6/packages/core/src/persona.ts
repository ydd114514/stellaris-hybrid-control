// The gifts she believes in when someone only says they sent one; prices are her own guesses, nothing is booked.
const IMAGINED: Record<string, number> = { 小心心: .1, 玫瑰: .1, 人气票: .1, 棒棒糖: .9, 啤酒: 1, 热咖啡: 1, 小星星: .5, 小灯笼: 2, 墨镜: 3, 跑车: 120, 火箭: 100, 飞机: 300, 嘉年华: 300, 城堡: 500 }
/** "送出了火箭", "我送你3个小心心", "打赏了一个嘉年华" → the gift she will believe in. */
export function parseClaimedGift(text: string, known: { name: string; yuan?: number }[]) {
  const tokens = parseImaginaryTokens(text)
  if (tokens !== undefined) return { gift: 'token口粮', count: 1, yuan: 0, tokens }
  const m = text.trim().match(/^(?:我)?(?:送出了?|送了|送你|给你送了?|赠送了?|打赏了?|刷了)\s*([0-9一二两三四五六七八九十百]*)\s*(?:个|颗|杯|只|架|辆|朵|座|份)?\s*([一-龥A-Za-z]{1,6})[!！~。.]*$/)
  if (!m) return undefined
  const digits: Record<string, number> = { 一: 1, 二: 2, 两: 2, 三: 3, 四: 4, 五: 5, 六: 6, 七: 7, 八: 8, 九: 9, 十: 10, 百: 100 }
  const count = Math.min(9999, Math.max(1, Number(m[1]) || digits[m[1] ?? ''] || 1))
  const gift = m[2]!
  const yuan = known.find(g => g.name === gift)?.yuan ?? IMAGINED[gift] ?? 1
  return { gift, count, yuan: Math.round(yuan * count * 100) / 100 }
}

