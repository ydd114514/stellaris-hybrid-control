/** Keeps the existing API name while covering the actual local day as well as the night. */
export function nightMood(at: number) {
  const { phase, hour } = getShopTime(at)
  if (phase === 'morning') return '现在是晨间，精神清爽，招呼客人慢慢开始一天，不默认大家熬了夜。'
  if (phase === 'day') return '现在是白天，清醒有活力，陪客人忙里偷闲，不默认现在是深夜。'
  if (phase === 'dusk') return '现在是黄昏，语气放松，陪客人从忙碌里缓一缓，不默认到了半夜。'
  if (hour >= 20) return '现在是夜晚，精神不错，招呼晚间来歇脚的客人。'
  if (hour < 2) return '过了零点，开始有点困，嘴更碎，偶尔打个小哈欠。'
  if (hour < 5) return '后半夜，困得迷迷糊糊，说话软乎乎的，更容易心软。'
  return '清晨六点以前，语气柔和，陪还醒着的客人歇一会，不宣称即将打烊。'
}

